#!/usr/bin/env bash
# bootstrap.sh — инициализация репозитория Second Brain PKB.
#
# Использование:
#   ./bootstrap.sh                        # только структура + файлы
#   ./bootstrap.sh --git                  # + первый коммит + тег iter-000
#   ./bootstrap.sh --git --yes            # без подтверждения
#   ./bootstrap.sh --force                # перезаписать существующие файлы
#   ./bootstrap.sh --git --force --yes    # полный сброс и коммит
#
# Требования: bash 4+, git (для --git).

set -euo pipefail

DO_GIT=false
FORCE=false
AUTO_YES=false

for arg in "$@"; do
  case "$arg" in
    --git)    DO_GIT=true ;;
    --force)  FORCE=true ;;
    --yes|-y) AUTO_YES=true ;;
    -h|--help)
      sed -n '2,20p' "$0" | sed 's/^# \{0,1\}//'
      exit 0 ;;
    *)
      echo "Неизвестный аргумент: $arg" >&2
      exit 1 ;;
  esac
done

say()  { printf '%s\n' "$*"; }
ok()   { printf '  ✓ %s\n' "$*"; }
skip() { printf '  · %s\n' "$*"; }

put() {
  local path="$1"
  if [[ -f "$path" && "$FORCE" != true ]]; then
    skip "$path (уже есть, пропущено)"
    cat > /dev/null
    return
  fi
  mkdir -p "$(dirname "$path")"
  cat > "$path"
  ok "$path"
}

# --- Проверка окружения ---
if [[ -d ".git" ]]; then
  say "→ Обнаружен .git (репозиторий уже инициализирован)"
elif [[ -n "$(ls -A . 2>/dev/null || true)" ]]; then
  say "⚠ Каталог не пустой и не является git-репозиторием."
  if [[ "$AUTO_YES" != true ]]; then
    read -rp "Продолжить? [y/N] " yn
    [[ "$yn" =~ ^[Yy]$ ]] || { say "Отменено."; exit 1; }
  fi
fi

# --- 1. Структура папок ---
say ""
say "→ Создаю структуру папок"
for d in \
  docs \
  docs/project-map \
  docs/decisions \
  docs/adr \
  docs/metamodel \
  docs/glossary \
  docs/validation \
  docs/_workflow \
  docs/_workflow/iterations \
  schema \
  plugin \
  examples \
  scripts \
; do
  mkdir -p "$d"
done

# --- 2. .gitkeep в пустых папках ---
say ""
say "→ Расставляю .gitkeep"
for d in docs/adr docs/metamodel docs/glossary docs/validation \
         docs/_workflow/iterations schema plugin examples scripts; do
  if [[ ! -f "$d/.gitkeep" ]]; then
    : > "$d/.gitkeep"
    ok "$d/.gitkeep"
  else
    skip "$d/.gitkeep"
  fi
done

# --- 3. Корневые файлы ---
say ""
say "→ Корневые файлы"

