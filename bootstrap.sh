## Коммиты — правила
- Формат: Conventional Commits (`feat:`, `docs:`, `refactor:`, `fix:`, `chore:`).
- Коммит A — только TASK.md и артефакты разбора. Артефактов реализации там нет.
- Коммит B — только артефакты реализации и отчёт. TASK следующей итерации там нет.
- Тело коммита B: `iteration: iter-NNN` + 1–2 строки сути.
- Один коммит = одна итерация (или одна доработка `-rK`).

## Теги
- `iter-000` — baseline, ставится один раз перед первой итерацией.
- `iter-NNN` — аннотированный, на коммите B принятой итерации.
- Доработки `-rK` тегов не получают. Тег `iter-NNN` — только финал серии.
- Аннотация: `iter-NNN: <краткая суть результата>`.

## Ветки для экспериментов
Единственный случай использования веток — рискованный эксперимент.
- Ветка `exp/NNN-краткое-имя` создаётся вручную человеком.
- Работа в ней по тому же протоколу (два коммита, `iterations/`).
- По итогам: `git merge --no-ff` в `main` (и новый тег) либо `git branch -D` без следа.
- Итерации эксперимента получают ID в диапазоне **900–999** (`iter-9NN`), чтобы не путались с основным потоком.

## Правила безопасности
- Перед `git push --force` — проверить, что тег с последней хорошей точкой существует и запушен.
- Перед удалением любого файла — проверить, что он не упомянут в `PROJECT_MAP`, `CHECKPOINT`, `OPEN_QUESTIONS`.
- Секреты и токены — никогда в промпты ИИ, только через локальный `git config`.

