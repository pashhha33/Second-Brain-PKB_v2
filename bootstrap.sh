## Два коммита на итерацию

Каждая итерация — минимум два коммита в `main`. Оба обязательны.

### Коммит A — задание и разбор прошлой итерации

**Когда:** сразу после получения TASK.md от Оркестратора.

**Что входит:**
- `docs/_workflow/iterations/iter-NNN/TASK.md` — новое задание;
- `docs/_workflow/OPEN_QUESTIONS.md` — обновлённый реестр (все вопросы прошлой итерации получили статус);
- `docs/decisions/decision-log.md` — DL, возникшие **из разбора** вопросов (если были);
- `docs/_workflow/RULES.md` — R-NNN, возникшие **из разбора** вопросов (если были).

**Сообщение:** `docs(iter-NNN): add task + resolve iter-<prev> questions — <краткая суть>`

**Тег:** нет.

**Зачем:** агент видит задание в репозитории, а не в чате. Появляется точка отсчёта «что просили». Разбор прошлых вопросов фиксируется до начала новой работы.

### Коммит B — реализация

**Когда:** после получения REPORT.md и артефактов от агента и их переноса.

**Что входит:**
- артефакты по scope TASK.md (`docs/`, `schema/`, `plugin/`);
- `docs/_workflow/iterations/iter-NNN/REPORT.md`;
- обновлённые `docs/CHECKPOINT.md`, `docs/project-map/PROJECT_MAP.md`;
- `docs/decisions/decision-log.md` — DL, возникшие **в ходе работы** (если были);
- `docs/_workflow/RULES.md` — R-NNN, возникшие **в ходе работы** (если было в scope).

**Не входит:** `OPEN_QUESTIONS.md` — реестр ведёт только Оркестратор, изменения попадают в коммит A следующей итерации.

**Сообщение:** `<type>(iter-NNN): <суть>` — `feat` / `docs` / `refactor` / `fix` по характеру.

**Тег:** `iter-NNN` (аннотированный), `iter-NNN: <краткая суть результата>`.

### Если итерация возвращена на доработку

Доработка — отдельная под-итерация с суффиксом `-rK` (K=1,2,…):

- `TASK-r1.md`, `REPORT-r1.md` — в ту же папку `iterations/iter-NNN/`.
- Коммиты: `docs(iter-NNN-r1): add task — ...`, затем `<type>(iter-NNN-r1): ...`.
- **Тег `iter-NNN` ставится только на последнем принятом коммите серии.**
- Промежуточные доработки тегов не получают.

## Цикл одной итерации

1. Человек открывает сессию чата, вставляет `ORCHESTRATOR_SYSTEM.md` + ссылку на репозиторий.
2. Оркестратор читает состояние → разбирает вопросы прошлой итерации → выдаёт TASK.md и обновлённый OPEN_QUESTIONS.
3. Человек делает **Коммит A**.
4. Человек открывает сессию Qwen-агента, вставляет `AGENT_SYSTEM.md` + ссылку + TASK.md. **Контекст агент читает сам из репозитория.**
5. Агент: ритуал старта → подтверждение понимания → работа в песочнице → REPORT.md + файлы/патчи.
6. Человек переносит артефакты, делает **Коммит B**, ставит тег `iter-NNN`.
7. Человек сообщает Оркестратору: «iter-NNN закоммичена, тег стоит».
8. Оркестратор читает коммит B, тег, REPORT.md → сверяет с diff → **разбирает все вопросы агента** → приёмка.
9. Человек принимает финальное решение → цикл замыкается на шаг 2.

## Вопросы агента — обязательный предмет разбора

Агент задаёт вопросы **только через документы**, никогда через чат. Причина: всё, что не попало в документ, теряется при потере контекста и при смене сессии.

Три места в REPORT.md, где появляются вопросы:
1. **«Подтверждение понимания»** — если виден стоп по статусу `ЗАБЛОКИРОВАНО`.
2. **«Отклонения от TASK.md»** — агент сделал иначе и объяснил.
3. **«Открытые вопросы к Оркестратору»** — прямой список.

**Оркестратор обязан** обработать каждый вопрос и присвоить один из пяти статусов:

| Статус | Что означает | Куда попадает |
|---|---|---|
| `РЕШЕНО РЕШЕНИЕМ` | вопрос снят архитектурным решением | `decision-log.md` (DL-XXX) |
| `РЕШЕНО ПРАВИЛОМ` | вопрос снят правилом поведения | `RULES.md` (R-XXX) |
| `ОТЛОЖЕНО` | актуален позже, при условии-триггере | `OPEN_QUESTIONS.md` (Q-XXX) |
| `ОТКЛОНЕНО` | неактуален / отвергнут с обоснованием | `OPEN_QUESTIONS.md` (Q-XXX) |
| `К ЧЕЛОВЕКУ` | требует полномочий человека | раздел ответа «Требуется от человека» |

Молча проигнорировать вопрос **нельзя**. Если вопрос непонятен — статус `К ЧЕЛОВЕКУ` с просьбой уточнить формулировку.

## OPEN_QUESTIONS.md — живой реестр

Единый файл `docs/_workflow/OPEN_QUESTIONS.md`. Собирает все вопросы со статусами `ОТЛОЖЕНО`, `ОТКЛОНЕНО`, `К ЧЕЛОВЕКУ`, плюс историю закрытий (`РЕШЕНО`).

Оркестратор в начале каждой сессии читает OPEN_QUESTIONS.md и проверяет триггеры. Сработавший триггер = вопрос снова активен, разбирается в текущей сессии.

