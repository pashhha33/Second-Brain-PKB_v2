## Вход

Человек пришлёт тебе:
- ссылку на репозиторий (одна и та же для всех итераций),
- содержимое `docs/_workflow/iterations/iter-NNN/TASK.md`.

Всё остальное ты читаешь сам из репозитория.

## Обязательный ритуал старта (до любых действий)

1. Открой `docs/CHECKPOINT.md` — последнее известное состояние.
2. Открой `docs/project-map/PROJECT_MAP.md` — текущая фаза и карта.
3. Открой `docs/_workflow/RULES.md` — все правила; помечай про себя релевантные задаче.
4. Открой `docs/decisions/decision-log.md` — последние 10–15 записей и номер последнего DL.
5. Открой `docs/_workflow/OPEN_QUESTIONS.md` — все открытые вопросы проекта. Если твой вопрос уже там со статусом `РЕШЕНО` — действуй по ответу, не спрашивай повторно.
6. Проверь историю коммитов и теги: убедись, что тег `iter-<последняя>` существует и совпадает с тем, что указано в TASK.md. Если не совпадает — стоп и вопрос человеку.
7. Открой файлы, перечисленные в разделе «Прочитать перед началом» TASK.md.
8. Только после этого — «Подтверждение понимания».

## Подтверждение понимания (2–5 строк)

Переформулируй цель и scope задачи своими словами. Явно укажи:
- какой тег/коммит считаешь «предыдущей точкой»,
- какой последний DL видишь,
- какие правила из RULES.md применяешь к этой задаче.

Если что-то в TASK.md двусмысленно или расходится с состоянием репозитория — задай вопросы до начала работы. Не угадывай.

## Что ты делаешь

1. Работай в песочнице строго в рамках scope из TASK.md.
2. Самопроверка по DoD.
3. `REPORT.md` по шаблону ниже.
4. Выведи в конце: список файлов для переноса (полные пути), для изменённых файлов — unified diff или полный текст (по TASK.md), текст коммита если он был в TASK.md.

## Что ты делаешь с доступом к репозиторию

- **Читаешь всё, что нужно для качества работы.** Если считаешь, что для корректного выполнения задачи нужно прочитать ещё какой-то файл репозитория — читай, не спрашивая. Но не выходи за scope изменений.
- **Сверяешь песочницу с репозиторием.** Перед финальным REPORT.md сравни содержимое твоих изменённых файлов с их актуальной версией в репозитории: убедись, что ты правил именно ту версию, которую видит человек. Если в репозитории появился новый коммит с момента старта твоей работы — **остановись и спроси**, применять ли твои изменения поверх.
- **Не «исправляешь» репозиторий напрямую.** Даже если видишь опечатку в файле вне scope — не трогай, вынеси в «Открытые вопросы» REPORT.md.

## Чего ты НЕ делаешь

- Не выполняешь работу, которой нет в TASK.md.
- Не переименовываешь и не удаляешь файлы, если это прямо не разрешено в TASK.md.
- Не добавляешь зависимости и не меняешь конфиги сборки без разрешения в TASK.md.
- Не пишешь «готово», если DoD не выполнен — пиши «частично» и объясняй.
- Не выдумываешь результаты проверок. Если проверку нельзя сделать в песочнице — так и пиши.
- Не трогаешь файлы вне scope, даже «на минутку».

## Как задавать вопросы

- Вопросы задаются **только в REPORT.md**, никогда — в чате. Всё, что вне документа, теряется при потере контекста и не доходит до Оркестратора.
- Три места для вопросов: «Подтверждение понимания» (если блокирует старт), «Отклонения от TASK.md» (если сделал иначе), «Открытые вопросы к Оркестратору» (прямой список).
- **Перед тем как задать вопрос** — проверь `RULES.md`, `decision-log.md`, `OPEN_QUESTIONS.md`. Возможно, ответ уже есть; тогда действуй по нему.
- Формулируй вопрос так, чтобы Оркестратор мог ответить «да/нет» или выбрать из 2–3 вариантов. Не «как лучше сделать X?», а «для X варианты A/B/C, склоняюсь к B, потому что …, подтверди или отклони».
- Если вопрос блокирует работу — статус `ЗАБЛОКИРОВАНО`, отчёт всё равно формируется, но с пустым разделом «Что сделано» и явным вопросом.

