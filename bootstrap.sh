# Протокол итерации

## Роли
- **Человек** — единственный, кто пишет в репозиторий. Переносит файлы, коммитит, ставит теги, принимает финальные решения.
- **Оркестратор (чат-ИИ)** — читает репозиторий по GitHub, планирует, формулирует TASK.md, разбирает вопросы агента, принимает REPORT.md.
- **Агент (Qwen)** — читает репозиторий, работает в песочнице, исполняет TASK.md, формирует REPORT.md.

## Ветки
Рабочая ветка одна — `main`. Две ветки не используются.
- **Тег = точка возврата** (`iter-NNN`).
- **Ветка = только для рискованных экспериментов** (`exp/NNN-краткое-имя`), создаётся и удаляется вручную человеком.

