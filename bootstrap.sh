| ADR | зафиксированные архитектурные решения с альтернативами |
| JSON Schema | машиночитаемые артефакты для проверки |
| Плагин Obsidian | реализация метамодели: TypeScript + Obsidian API |
| Примеры | эталонные экземпляры и шаблоны заметок |

