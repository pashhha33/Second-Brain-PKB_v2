## Видение

Личная база знаний, в которой структура не задана заранее жёстко, а описывается той же базой. Пользователь добавляет новый тип объекта, свойство или отношение — и система узнаёт о нём без изменения кода.

## Ключевые принципы

1. **Самоопределение.** Тип — это объект. Свойство — объект. Отношение — объект. Всё имеет `id` и `type`.
2. **Расширяемость без правки плагина.** Новый тип = новая заметка, а не новая версия кода.
3. **Явная семантика.** У каждого объекта есть слой (схема / экземпляр), статус (черновик / принято) и владелец.
4. **Проверяемость.** Правила валидации — тоже объекты; их можно добавлять и отключать.

## Что входит в проект

| Часть | Назначение |
